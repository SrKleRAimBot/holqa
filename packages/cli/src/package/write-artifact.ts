import type { ArtifactDescriptor } from "@holqa/container";
import type { Diagnostic } from "@holqa/core";

import {
  cp,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile
} from "node:fs/promises";
import {
  dirname,
  join,
  relative,
  sep
} from "node:path";

import { canonicalJsonStringify } from "@holqa/compiler";
import {
  artifactFileName,
  artifactFormat,
  sha256Hex
} from "@holqa/container";
import {
  createDiagnostic,
  diagnosticCodes,
  diagnosticsOf,
  HolqaError
} from "@holqa/core";

/** The bundled entry point's file name in an artifact. */
export const artifactEntry = "server.js";

/** Everything a deployment artifact is written from. */
export interface ArtifactRequest {
  /** The application root: the directory of the application module. */
  readonly root: string;
  /** The application module, absolute. */
  readonly appPath: string;
  /** The binding configuration module, absolute. */
  readonly bindingsPath: string;
  /** The output directory, absolute. */
  readonly outDir: string;
  readonly application: string;
  /** The binding configuration's name. */
  readonly bindingsName: string;
  /** The canonical application manifest text and its fingerprint. */
  readonly manifest: { readonly text: string; readonly fingerprint: string };
  /** The canonical binding manifest text. */
  readonly bindingManifest: string;
  /** Every handler's module (relative to the root) and export, in manifest order. */
  readonly handlers: readonly { readonly id: string; readonly module: string; readonly export: string }[];
  /** Static sites, with directories relative to the root. */
  readonly staticSites: readonly { readonly id: string; readonly directory: string }[];
  /** The container runtime module the entry point imports, absolute. */
  readonly containerModule: string;
  /** The Bun version the artifact needs and its reference image uses. */
  readonly bunVersion: string;
  /** The Bun executable that bundles. Default the running one. */
  readonly bunPath?: string;
}

/** A written artifact. */
export interface WrittenArtifact {
  readonly descriptor: ArtifactDescriptor;
  /** The `sha256:` fingerprint of `artifact.json`. */
  readonly fingerprint: string;
}

/**
 * Builds an `HOLQA_PACKAGE_FAILED` error.
 *
 * @param message - What failed.
 * @param hint - How to fix it.
 * @returns The error to throw.
 */
function failed(message: string, hint?: string): HolqaError {
  return new HolqaError(createDiagnostic({ code: diagnosticCodes.packageFailed, severity: "error", message, ...hint === undefined ? {} : { hint } }));
}

/**
 * Generates the entry point the bundler starts from: it imports the
 * application, its handlers and the binding configuration statically, so the
 * bundle contains exactly what the manifest names, and starts the container
 * runtime on the artifact directory.
 *
 * Specifiers are relative to the entry point, so the generated module and
 * the bundle's comments do not depend on where the project is checked out.
 *
 * @param request - The artifact request.
 * @param entryDir - The directory the entry point is written to.
 * @returns The module's source text.
 */
export function entrySource(request: ArtifactRequest, entryDir: string): string {
  const modules = [...new Set(request.handlers.map(handler => handler.module))];
  /**
   * Builds a relative import specifier from the entry point's directory.
   *
   * @param path - The imported module, absolute.
   * @returns A `./` or `../` specifier with `/` separators.
   */
  const specifier = (path: string): string => {
    const portable = relative(entryDir, path).split(sep).join("/");
    return JSON.stringify(portable.startsWith(".") ? portable : `./${portable}`);
  };
  const lines = [
    "// Generated by holqa package. Do not edit: package the application again instead.",
    `import { runContainer } from ${specifier(request.containerModule)};`,
    `import app from ${specifier(request.appPath)};`,
    `import bindings from ${specifier(request.bindingsPath)};`,
    ...modules.map((module, index) => `import * as handlers${index} from ${specifier(join(request.root, module))};`),
    "",
    "const handlers = [",
    ...request.handlers.map((handler, index) => `  handlers${modules.indexOf(handler.module)}[${JSON.stringify(handler.export)}]${index < request.handlers.length - 1 ? "," : ""}`),
    "];",
    "",
    "await runContainer({ app, handlers, bindings, directory: import.meta.dir });",
    ""
  ];
  return lines.join("\n");
}

/**
 * Generates a reference Dockerfile: the artifact on the official Bun image of
 * the packaging Bun version, run as the image's unprivileged user, with the
 * readiness probe as health check and `SIGTERM` for graceful shutdown.
 *
 * @param bunVersion - The packaging Bun's version, which selects the base image tag.
 * @returns The Dockerfile's text.
 */
export function dockerfile(bunVersion: string): string {
  return [
    "# Generated by holqa package: a reference image for this artifact. Review it before use.",
    `FROM oven/bun:${bunVersion}-slim`,
    "WORKDIR /app",
    "COPY --chown=bun:bun . .",
    "ENV NODE_ENV=production HOST=0.0.0.0 PORT=3000",
    "USER bun",
    "EXPOSE 3000",
    "STOPSIGNAL SIGTERM",
    // The probe script is shell-free JSON exec form; the template literal is evaluated by the probe's Bun, not here.
    `HEALTHCHECK --interval=10s --timeout=3s --start-period=15s CMD ["bun", "-e", "const response = await fetch(\`http://127.0.0.1:\${process.env.PORT ?? 3000}/.holqa/ready\`); process.exit(response.ok ? 0 : 1)"]`,
    `CMD ["bun", "${artifactEntry}"]`,
    ""
  ].join("\n");
}

/**
 * Lists every file under a directory, recursively.
 *
 * @param directory - The root of the walk.
 * @returns Absolute file paths.
 */
async function filesUnder(directory: string): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory())
      files.push(...await filesUnder(path));
    else if (entry.isFile())
      files.push(path);
  }
  return files;
}

/**
 * Clears the output directory, but only when it is empty or holds a previous
 * artifact: packaging never deletes a directory it did not write.
 *
 * @param outDir - The output directory.
 * @throws {HolqaError} `HOLQA_PACKAGE_FAILED` for a non-empty directory without `artifact.json`.
 */
async function prepareOutDir(outDir: string): Promise<void> {
  const entries = await readdir(outDir).catch(() => undefined);
  if (entries !== undefined && entries.length > 0) {
    if (!entries.includes(artifactFileName))
      throw failed(`The output directory ${outDir} is not empty and holds no previous artifact.`, "Choose an empty directory with --out-dir; holqa package only replaces its own output.");
    await rm(outDir, { recursive: true, force: true });
  }
  await mkdir(outDir, { recursive: true });
}

/**
 * Writes a deployment artifact: the bundled application and container
 * runtime (`server.js`, bundled by `bun build` for the Bun target), the
 * application manifest, the binding manifest, the static sites' files, a
 * reference Dockerfile, and `artifact.json` with the SHA-256 of every file.
 * The same inputs produce the same files and hashes.
 *
 * Trust: bundling reads the application's modules but does not run them; the
 * analysis that produced the manifests did.
 *
 * Bun-specific: bundles with `bun build --target=bun` in a separate process.
 *
 * @param request - The application, manifests, handlers and output directory.
 * @returns The descriptor and its fingerprint.
 * @throws {HolqaError} `HOLQA_PACKAGE_FAILED` when a static site's directory is missing, bundling fails or a file cannot be written.
 */
export async function writeArtifact(request: ArtifactRequest): Promise<WrittenArtifact> {
  for (const site of request.staticSites) {
    if (!(await stat(join(request.root, site.directory)).catch(() => undefined))?.isDirectory())
      throw failed(`The static site "${site.id}" has no files: ${join(request.root, site.directory)} is not a directory.`, "Build the frontend before packaging, so its output directory exists.");
  }
  await prepareOutDir(request.outDir);
  // The entry lives in the application root, so its imports are "./" paths and the bundle's
  // module comments are root-relative and identical on every machine. It is removed after bundling.
  const entryPath = join(request.root, `.holqa-entry.${request.bindingsName.replace(/[^\w.-]/g, "_")}.ts`);
  await writeFile(entryPath, entrySource(request, request.root));
  try {
    // A separate `bun build` process: repeated in-process Bun.build calls are unreliable on Bun 1.3.13, and bundling stays isolated from the CLI.
    const { PATH: path = "" } = process.env;
    const child = Bun.spawn([request.bunPath ?? process.execPath, "build", entryPath, "--target=bun", "--format=esm", "--outfile", join(request.outDir, artifactEntry)], { cwd: request.root, env: { PATH: path }, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
    const [code, errors] = await Promise.all([child.exited, new Response(child.stderr).text()]);
    if (code !== 0)
      throw failed(`Bundling the application failed: ${errors.trim().split("\n").filter(line => /error/i.test(line)).join("; ") || errors.trim() || `bun build exited with ${code}`}.`, "Fix the reported imports; every module the application, handlers and binding configuration import must resolve.");
  } finally {
    await rm(entryPath, { force: true });
  }
  await writeFile(join(request.outDir, "manifest.json"), request.manifest.text);
  await writeFile(join(request.outDir, "bindings.json"), request.bindingManifest);
  await writeFile(join(request.outDir, "Dockerfile"), dockerfile(request.bunVersion));
  for (const site of request.staticSites) {
    const target = join(request.outDir, site.directory);
    await mkdir(dirname(target), { recursive: true });
    await cp(join(request.root, site.directory), target, { recursive: true });
  }
  const files: Array<ArtifactDescriptor["files"][number]> = [];
  for (const path of await filesUnder(request.outDir)) {
    const bytes = new Uint8Array(await readFile(path));
    files.push({ path: relative(request.outDir, path).split(sep).join("/"), sha256: sha256Hex(bytes), bytes: bytes.length });
  }
  files.sort((left, right) => left.path < right.path ? -1 : left.path > right.path ? 1 : 0);
  const descriptor: ArtifactDescriptor = {
    format: artifactFormat,
    application: request.application,
    manifest: request.manifest.fingerprint,
    bindings: request.bindingsName,
    entry: artifactEntry,
    runtime: { bun: request.bunVersion },
    staticSites: request.staticSites.map(site => ({ id: site.id, directory: site.directory })),
    files
  };
  const text = `${canonicalJsonStringify(descriptor)}\n`;
  await writeFile(join(request.outDir, artifactFileName), text);
  return { descriptor, fingerprint: `sha256:${sha256Hex(new TextEncoder().encode(text))}` };
}

/**
 * Converts a failure while writing into diagnostics.
 *
 * @param error - What was thrown.
 * @param outDir - The output directory, for the message.
 * @returns The diagnostics to report.
 */
export function packageFailure(error: unknown, outDir: string): Diagnostic[] {
  if (error instanceof HolqaError)
    return [...diagnosticsOf(error)];
  return [createDiagnostic({ code: diagnosticCodes.packageFailed, severity: "error", message: `Writing the artifact to ${outDir} failed: ${error instanceof Error ? error.message : String(error)}.`, hint: "Check that the output directory is writable." })];
}